declare(strict_types=1);

/**
 * Load an ACL dataset, freeze the centreon_acl rows computed for it, check them, or run the CI scenarios.
 *
 * Usage:
 *   php qualify.php load <dataset.sql>      run a dataset generated by gen.php on the configuration database
 *   php qualify.php export > expected.sql   write the centreon_acl rows of the dataset groups as an expected file
 *   php qualify.php check <expected.sql>    compare centreon_acl with the expected file (exit 1 on any difference)
 *   php qualify.php scenarios <size> [--baseline <cron directory> [--baseline-ref <branch>] [--baseline-commit <sha>]]
 *                                           remove any previous dataset, load dataset-<size>.sql, then run
 *                                           cron/centAcl.php in the eight scenarios below (exit 1 on any failure)
 *
 * Scenarios, with every access group and resource of the dataset flagged as changed before each run:
 *   A. empty table: the computed rows must equal expected-<size>.sql, all of them inserted;
 *   B. nothing changed: a second run, the rows must still equal expected-<size>.sql, every group skipped thanks to
 *      its fingerprint and no row written;
 *   C. small change: hosts added to and removed from a host group; the rows must equal those of a full recompute
 *      on an empty table, and only the changed rows be written;
 *   D. rows deleted outside the cron, fingerprints kept: every row must be written again;
 *   E. a row inserted outside the cron, the fingerprint of its group removed as the other writers of centreon_acl do:
 *      that group only is written again, the row deleted;
 *   F. a disabled access group: its rows and its fingerprint must go, the groups of centreon_acl being listed through
 *      its unique key (EXPLAIN), and the other groups skipped;
 *   G. no fingerprint table, as before the database upgrade: the rows must stay the same, no group skipped;
 *   H. a write error on a group, the resource accesses flagged as "Reload ACL" does: the group must keep its rows,
 *      its resource accesses their flag, and centAcl.php must release its lock, so that once the cause is gone, the
 *      next run writes the group again.
 * Every run of centAcl.php is timed, with its PHP peak memory, max resident size and writes (measure.php). The writes
 * the engine reports are checked: a run that reports none fails. The scenarios print their report as plain-text tables,
 * and append it in Markdown to the GitHub job summary when $GITHUB_STEP_SUMMARY is set.
 *
 * With --baseline, the cron scripts of that directory (those of the target branch, in CI) and the current ones are
 * measured on the same machine, after the scenarios: B and C, 3 runs each, alternately, median kept. As both engines
 * run on the same machine, the comparison does not depend on its speed. The scenarios fail when the current engine is
 * more than 20 % slower than the baseline, or uses more than 5 % more PHP memory, in B or C. The other scenarios, rare,
 * are not compared. --baseline-ref and --baseline-commit name the Git branch and commit the baseline cron scripts come
 * from, for the report.
 *
 * The databases are the ones of the Centreon configuration (config/centreon.config.php), the same as centAcl.php.
 * The dataset ids are fixed (ids.php): use a database that holds no other object in these ranges, such as the CI one.
 */

require_once __DIR__ . '/ids.php';

// Every access group of a dataset has an id at or above this base.
const FIRST_DATASET_GROUP_ID = B;
const EXPECTED_TABLE = 'centreon_acl_expected';
const SAMPLE_SIZE = 20;

// Small change of scenario C: on the first host group of the dataset, which grants rights to several groups.
const CHANGED_HOST_GROUP_ID = B;
const ADDED_HOSTS = 20;
const REMOVED_HOSTS = 5;

// Write error of scenario H: the check constraint that rejects a row of the group.
const WRITE_ERROR_CONSTRAINT = 'acl_qualify_write_error';

// Comparison with a baseline engine: runs per scenario (median kept), the slowdown allowed for the variations of a
// shared machine, and the PHP memory growth allowed for the code a pull request adds to the files the cron loads.
const COMPARISON_RUNS = 3;
const ALLOWED_SLOWDOWN = 1.2;
const ALLOWED_MEMORY_GROWTH = 1.05;

const EXIT_IDENTICAL = 0;
const EXIT_DIFFERENT = 1;
const EXIT_ERROR = 2;

/**
 * @param array<string, string> $settings the $conf_centreon array of centreon.conf.php
 * @param 'db'|'dbcstg' $databaseKey
 */
function connect(array $settings, string $databaseKey): PDO
{
    $host = $databaseKey === 'dbcstg' ? $settings['hostCentstorage'] : $settings['hostCentreon'];

    return new PDO(
        sprintf('mysql:host=%s;port=%s;dbname=%s', $host, $settings['port'], $settings[$databaseKey]),
        $settings['user'],
        $settings['password'],
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION],
    );
}

/**
 * Runs the statements of a generated SQL file one by one, so that an error in any of them stops the run
 * (PDO::exec() on a multi-statement string only reports an error of the first statement).
 *
 * Generated files end every statement with ";" at the end of a line, and comments are full "--" lines.
 */
function runSqlFile(PDO $pdo, string $path): int
{
    $content = file_get_contents($path);
    if ($content === false) {
        throw new RuntimeException("Cannot read {$path}");
    }
    $lines = array_filter(
        explode("\n", $content),
        static fn (string $line): bool => ! str_starts_with(ltrim($line), '--'),
    );
    $statements = array_filter(
        array_map('trim', preg_split('/;\s*$/m', implode("\n", $lines)) ?: []),
        static fn (string $statement): bool => $statement !== '',
    );
    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }

    return count($statements);
}

function load(PDO $configuration, string $datasetPath): int
{
    $count = runSqlFile($configuration, $datasetPath);
    fwrite(STDERR, "{$count} statements run from {$datasetPath}\n");

    return EXIT_IDENTICAL;
}

/**
 * One INSERT per access group and one row per line: a change in the computed rows shows up in the diff of the
 * expected file as the changed rows only.
 *
 * @param resource $output
 */
function writeExpected(PDO $storage, $output): int
{
    $statement = $storage->prepare(
        'SELECT group_id, host_id, service_id FROM centreon_acl WHERE group_id >= :firstGroupId '
        . 'ORDER BY group_id, host_id, service_id',
    );
    $statement->bindValue(':firstGroupId', FIRST_DATASET_GROUP_ID, PDO::PARAM_INT);
    $statement->execute();

    fwrite($output, "-- Expected centreon_acl rows of the dataset access groups, computed by cron/centAcl.php.\n");
    fwrite($output, "-- Generated by \"php qualify.php export\": do not edit by hand.\n");
    $currentGroupId = null;
    $rowCount = 0;
    while (($row = $statement->fetch(PDO::FETCH_ASSOC)) !== false) {
        $groupId = (int) $row['group_id'];
        if ($groupId !== $currentGroupId) {
            fwrite($output, $currentGroupId === null ? '' : ";\n");
            fwrite($output, 'INSERT INTO ' . EXPECTED_TABLE . " (group_id, host_id, service_id) VALUES\n");
            $currentGroupId = $groupId;
        } else {
            fwrite($output, ",\n");
        }
        $serviceId = $row['service_id'] === null ? 'NULL' : (string) (int) $row['service_id'];
        fwrite($output, sprintf('(%d,%d,%s)', $groupId, (int) $row['host_id'], $serviceId));
        $rowCount++;
    }
    fwrite($output, $currentGroupId === null ? '' : ";\n");

    return $rowCount;
}

function export(PDO $storage): int
{
    $rowCount = writeExpected($storage, STDOUT);
    fwrite(STDERR, "{$rowCount} rows exported\n");

    return $rowCount > 0 ? EXIT_IDENTICAL : EXIT_ERROR;
}

/**
 * @return list<array{group_id: int, host_id: int, service_id: int|null}>
 */
function rowsOnlyIn(PDO $pdo, string $leftQuery, string $rightQuery): array
{
    // EXCEPT ALL compares the number of copies of each row too (a host row can be written twice: its NULL service id
    // escapes the unique key), and treats two NULL service ids as equal.
    $statement = $pdo->prepare(
        "{$leftQuery} EXCEPT ALL {$rightQuery} ORDER BY group_id, host_id, service_id",
    );
    $statement->bindValue(':firstGroupId', FIRST_DATASET_GROUP_ID, PDO::PARAM_INT);
    $statement->execute();

    return array_map(
        static fn (array $row): array => [
            'group_id' => (int) $row['group_id'],
            'host_id' => (int) $row['host_id'],
            'service_id' => $row['service_id'] === null ? null : (int) $row['service_id'],
        ],
        $statement->fetchAll(PDO::FETCH_ASSOC),
    );
}

/**
 * Compares the centreon_acl rows of the dataset groups with an expected file, both ways.
 *
 * @return array{
 *     expected: int,
 *     computed: int,
 *     unexpected: list<array{group_id: int, host_id: int, service_id: int|null}>,
 *     missing: list<array{group_id: int, host_id: int, service_id: int|null}>
 * } computed: the number of centreon_acl rows checked
 */
function compare(PDO $storage, string $expectedPath): array
{
    $storage->exec('DROP TABLE IF EXISTS ' . EXPECTED_TABLE);
    $storage->exec(
        'CREATE TABLE ' . EXPECTED_TABLE . ' (group_id INT NOT NULL, host_id INT NOT NULL, service_id INT NULL, '
        . 'KEY (group_id, host_id, service_id)) ENGINE=InnoDB',
    );

    try {
        runSqlFile($storage, $expectedPath);
        $expectedCount = (int) $storage->query('SELECT COUNT(*) FROM ' . EXPECTED_TABLE)->fetchColumn();
        if ($expectedCount === 0) {
            throw new RuntimeException("No expected rows in {$expectedPath}");
        }

        $computed = 'SELECT group_id, host_id, service_id FROM centreon_acl WHERE group_id >= :firstGroupId';
        $expected = 'SELECT group_id, host_id, service_id FROM ' . EXPECTED_TABLE;
        $computedCount = (int) $storage->query(
            'SELECT COUNT(*) FROM centreon_acl WHERE group_id >= ' . FIRST_DATASET_GROUP_ID,
        )->fetchColumn();

        return [
            'expected' => $expectedCount,
            'computed' => $computedCount,
            'unexpected' => rowsOnlyIn($storage, $computed, $expected),
            'missing' => rowsOnlyIn($storage, $expected, $computed),
        ];
    } finally {
        $storage->exec('DROP TABLE IF EXISTS ' . EXPECTED_TABLE);
    }
}

/**
 * @param list<array{group_id: int, host_id: int, service_id: int|null}> $rows
 */
function report(string $title, array $rows): void
{
    fwrite(STDERR, sprintf("%s: %d\n", $title, count($rows)));
    foreach (array_slice($rows, 0, SAMPLE_SIZE) as $row) {
        fwrite(STDERR, sprintf(
            "  group %d, host %d, service %s\n",
            $row['group_id'],
            $row['host_id'],
            $row['service_id'] === null ? '(host row)' : (string) $row['service_id'],
        ));
    }
}

/**
 * @param array{
 *     expected: int,
 *     computed: int,
 *     unexpected: list<array{group_id: int, host_id: int, service_id: int|null}>,
 *     missing: list<array{group_id: int, host_id: int, service_id: int|null}>
 * } $comparison
 */
function isIdentical(array $comparison): bool
{
    return $comparison['unexpected'] === [] && $comparison['missing'] === [];
}

function check(PDO $storage, string $expectedPath): int
{
    $comparison = compare($storage, $expectedPath);
    fwrite(STDERR, "{$comparison['expected']} expected rows\n");
    report('Unexpected rows (visibility leak)', $comparison['unexpected']);
    report('Missing rows (lost visibility)', $comparison['missing']);

    return isIdentical($comparison) ? EXIT_IDENTICAL : EXIT_DIFFERENT;
}

/**
 * Removes every object of a previous dataset and its centreon_acl rows, so that the next dataset can be loaded with
 * the same fixed ids.
 */
function removeDataset(PDO $configuration, PDO $storage): void
{
    $statements = [
        'DELETE FROM acl_resources_sc_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_resources_hc_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_resources_sg_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_resources_hostex_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_resources_host_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_resources_hg_relations WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_res_group_relations WHERE acl_res_id >= ' . B . ' OR acl_group_id >= ' . B,
        'DELETE FROM acl_resources WHERE acl_res_id >= ' . B,
        'DELETE FROM acl_group_contactgroups_relations WHERE acl_group_id >= ' . B,
        'DELETE FROM acl_group_contacts_relations WHERE acl_group_id >= ' . B,
        'DELETE FROM acl_groups WHERE acl_group_id >= ' . B,
        'DELETE FROM contactgroup_contact_relation WHERE contactgroup_cg_id >= ' . B,
        'DELETE FROM contactgroup WHERE cg_id >= ' . B,
        'DELETE FROM contact WHERE contact_id >= ' . B,
        'DELETE FROM hostcategories_relation WHERE hostcategories_hc_id >= ' . B,
        'DELETE FROM hostcategories WHERE hc_id >= ' . B,
        'DELETE FROM servicegroup_relation WHERE servicegroup_sg_id >= ' . B,
        'DELETE FROM servicegroup WHERE sg_id >= ' . B,
        'DELETE FROM hostgroup_relation WHERE hostgroup_hg_id >= ' . B,
        'DELETE FROM hostgroup WHERE hg_id >= ' . B,
        'DELETE FROM host_service_relation WHERE host_host_id >= ' . B_HTPL,
        'DELETE FROM service_categories_relation WHERE service_service_id >= ' . B_STPL,
        'DELETE FROM service WHERE service_id >= ' . B_STPL,
        'DELETE FROM service_categories WHERE sc_id >= ' . B,
        'DELETE FROM ns_host_relation WHERE host_host_id >= ' . B_HTPL,
        'DELETE FROM nagios_server WHERE id >= ' . B,
        'DELETE FROM host_template_relation WHERE host_host_id >= ' . B_HTPL,
        'DELETE FROM host WHERE host_id >= ' . B_HTPL,
    ];
    // The deletions follow no dependency order: the foreign key checks are off for this session only.
    $configuration->exec('SET foreign_key_checks = 0');
    try {
        foreach ($statements as $statement) {
            $configuration->exec($statement);
        }
    } finally {
        $configuration->exec('SET foreign_key_checks = 1');
    }
    clearComputedRows($storage);
}

/**
 * Flags every access group and resource of the dataset as changed, like "Reload ACL": centAcl.php recomputes them all.
 */
function flagDataset(PDO $configuration): void
{
    $configuration->exec("UPDATE acl_groups SET acl_group_changed = '1' WHERE acl_group_id >= " . B);
    $configuration->exec("UPDATE acl_resources SET changed = '1' WHERE acl_res_id >= " . B);
}

/**
 * Removes the members of the changed host group with the highest ids, and adds the dataset hosts with the lowest ids
 * that are not members yet: the two sets never overlap.
 *
 * @return array{added: list<int>, removed: list<int>} the change, to revert it
 */
function applySmallChange(PDO $configuration): array
{
    $removed = array_map('intval', $configuration->query(
        'SELECT host_host_id FROM hostgroup_relation WHERE hostgroup_hg_id = ' . CHANGED_HOST_GROUP_ID
        . ' ORDER BY host_host_id DESC LIMIT ' . REMOVED_HOSTS,
    )->fetchAll(PDO::FETCH_COLUMN));
    $added = array_map('intval', $configuration->query(
        'SELECT h.host_id FROM host h '
        . 'WHERE h.host_id >= ' . B_HOST . " AND h.host_register = '1' "
        . 'AND NOT EXISTS (SELECT 1 FROM hostgroup_relation r WHERE r.hostgroup_hg_id = ' . CHANGED_HOST_GROUP_ID
        . ' AND r.host_host_id = h.host_id) '
        . 'ORDER BY h.host_id LIMIT ' . ADDED_HOSTS,
    )->fetchAll(PDO::FETCH_COLUMN));
    $change = ['added' => $added, 'removed' => $removed];
    setHostGroupMembers($configuration, $change['removed'], $change['added']);

    return $change;
}

/**
 * @param array{added: list<int>, removed: list<int>} $change
 */
function revertSmallChange(PDO $configuration, array $change): void
{
    setHostGroupMembers($configuration, $change['added'], $change['removed']);
}

/**
 * @param list<int> $hostIdsOut members removed from the changed host group
 * @param list<int> $hostIdsIn hosts added to it
 */
function setHostGroupMembers(PDO $configuration, array $hostIdsOut, array $hostIdsIn): void
{
    if ($hostIdsOut !== []) {
        $configuration->exec(
            'DELETE FROM hostgroup_relation WHERE hostgroup_hg_id = ' . CHANGED_HOST_GROUP_ID
            . ' AND host_host_id IN (' . implode(',', $hostIdsOut) . ')',
        );
    }
    foreach ($hostIdsIn as $hostId) {
        $configuration->exec(
            'INSERT INTO hostgroup_relation (hostgroup_hg_id, host_host_id) VALUES ('
            . CHANGED_HOST_GROUP_ID . ', ' . $hostId . ')',
        );
    }
}

/**
 * Removes the centreon_acl rows of the dataset groups, so that the next run recomputes them from an empty table.
 */
function clearComputedRows(PDO $storage): void
{
    $storage->exec('DELETE FROM centreon_acl WHERE group_id >= ' . B);
    // The fingerprints go too, otherwise the next run would skip the unchanged groups. The table is missing on a schema
    // that predates it.
    $fingerprintTable = $storage->query(
        'SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE() '
        . "AND table_name = 'centreon_acl_checksum'",
    )->fetchColumn();
    if ((int) $fingerprintTable > 0) {
        $storage->exec('DELETE FROM centreon_acl_checksum WHERE group_id >= ' . B);
    }
}

/**
 * Inserts, outside the cron, the host row of a host a group is not granted, and removes the fingerprint of the group, as
 * the other writers of centreon_acl do.
 */
function insertRowOutsideCron(PDO $storage, int $groupId): void
{
    $hostId = $storage->query(
        'SELECT MIN(a.host_id) FROM centreon_acl a WHERE a.group_id >= ' . B . ' AND NOT EXISTS ('
        . 'SELECT 1 FROM centreon_acl b WHERE b.group_id = ' . $groupId . ' AND b.host_id = a.host_id)',
    )->fetchColumn();
    if ($hostId === false || $hostId === null) {
        throw new RuntimeException("No host to insert in group {$groupId}");
    }
    $storage->exec(sprintf(
        'INSERT INTO centreon_acl (group_id, host_id, service_id) VALUES (%d, %d, NULL)',
        $groupId,
        (int) $hostId,
    ));
    $storage->exec('DELETE FROM centreon_acl_checksum WHERE group_id = ' . $groupId);
}

/**
 * Makes the next write of a group fail: one of its service rows is deleted outside the cron, with the fingerprint of
 * the group, so that the next run writes the group again, and a check constraint rejects that row.
 *
 * @return int the number of rows the group keeps until its rows are written again
 */
function prepareWriteError(PDO $storage, int $groupId): int
{
    $row = $storage->query(
        'SELECT host_id, service_id FROM centreon_acl WHERE group_id = ' . $groupId
        . ' AND service_id IS NOT NULL ORDER BY host_id, service_id LIMIT 1',
    )->fetch(PDO::FETCH_NUM);
    if ($row === false) {
        throw new RuntimeException("No service row in group {$groupId}");
    }
    $rowCondition = sprintf(
        'group_id = %d AND host_id = %d AND service_id = %d',
        $groupId,
        (int) $row[0],
        (int) $row[1],
    );
    $storage->exec("DELETE FROM centreon_acl WHERE {$rowCondition}");
    $storage->exec('DELETE FROM centreon_acl_checksum WHERE group_id = ' . $groupId);
    $storage->exec(
        'ALTER TABLE centreon_acl ADD CONSTRAINT ' . WRITE_ERROR_CONSTRAINT . " CHECK (NOT ({$rowCondition}))",
    );

    return (int) $storage->query('SELECT COUNT(*) FROM centreon_acl WHERE group_id = ' . $groupId)->fetchColumn();
}

/**
 * @return list<string> the problems found: a group whose write failed keeps its rows, and its resource accesses stay
 *     flagged as changed, so that a next run writes it again
 */
function checkFailedWrite(PDO $configuration, PDO $storage, int $groupId, int $rowCountBefore): array
{
    $problems = [];
    $rowCount = (int) $storage->query('SELECT COUNT(*) FROM centreon_acl WHERE group_id = ' . $groupId)->fetchColumn();
    if ($rowCount !== $rowCountBefore) {
        $problems[] = "the failed write left {$rowCount} rows instead of {$rowCountBefore}";
    }
    $unflagged = (int) $configuration->query(
        'SELECT COUNT(*) FROM acl_res_group_relations r '
        . 'JOIN acl_resources a ON a.acl_res_id = r.acl_res_id '
        . "WHERE r.acl_group_id = {$groupId} AND a.changed <> '1'",
    )->fetchColumn();
    if ($unflagged > 0) {
        $problems[] = "the failed write reset the flag of {$unflagged} resource accesses of the group";
    }
    // Otherwise the next run would only remove the lock, instead of writing the group again.
    $locked = (int) $configuration->query(
        "SELECT COUNT(*) FROM cron_operation WHERE name = 'centAcl.php' AND running = '1'",
    )->fetchColumn();
    if ($locked > 0) {
        $problems[] = 'centAcl.php kept its lock after the error';
    }

    return $problems;
}

/**
 * @return list<string> the problems found: a disabled group must keep no row and no fingerprint
 */
function checkStaleGroupRemoved(PDO $storage, int $groupId): array
{
    $problems = [];
    $rowCount = (int) $storage->query('SELECT COUNT(*) FROM centreon_acl WHERE group_id = ' . $groupId)->fetchColumn();
    if ($rowCount > 0) {
        $problems[] = "the disabled group kept {$rowCount} rows";
    }
    $fingerprintCount = (int) $storage->query(
        'SELECT COUNT(*) FROM centreon_acl_checksum WHERE group_id = ' . $groupId,
    )->fetchColumn();
    if ($fingerprintCount > 0) {
        $problems[] = 'the disabled group kept its fingerprint';
    }

    return $problems;
}

/**
 * The stale group cleanup (centAclPurgeStaleGroups()) lists the groups present in centreon_acl with the query below: it
 * must read the unique key group by group, not every row of the table.
 *
 * @return list<string> the problems found
 */
function checkStaleGroupListing(PDO $storage): array
{
    // Up-to-date statistics, so that the plan is the one of a table of this size.
    $storage->query('ANALYZE TABLE centreon_acl')->fetchAll();
    $plan = $storage->query('EXPLAIN SELECT DISTINCT group_id FROM centreon_acl')->fetch(PDO::FETCH_ASSOC);
    $extra = is_array($plan) ? (string) ($plan['Extra'] ?? '') : '';
    if (str_contains($extra, 'Using index for group-by')) {
        return [];
    }

    return ["listing the groups of centreon_acl reads every row (EXPLAIN: {$extra})"];
}

/**
 * Runs cron/centAcl.php, unmodified, with measure.php prepended: the one of this repository, or the one of a root built
 * by prepareEngineRoot().
 *
 * centAcl.php exits with code 0 even when it stops on an error (programExit()): the run only counts when every
 * dataset group has been processed, that is, when none of them is still flagged as changed.
 *
 * @return array{
 *     seconds: float,
 *     peak_bytes: int,
 *     max_rss_bytes: int,
 *     stats: array{groups: int, skipped: int, inserted: int, deleted: int}|null
 * } stats: what the run did to centreon_acl, null when the engine does not report it
 */
function runEngine(PDO $configuration, ?string $engineRoot = null): array
{
    $measureFile = tempnam(sys_get_temp_dir(), 'acl-measure-');
    if ($measureFile === false) {
        throw new RuntimeException('Cannot create a temporary file');
    }
    $command = [
        PHP_BINARY,
        '-d',
        'auto_prepend_file=' . __DIR__ . '/measure.php',
        ($engineRoot ?? dirname(__DIR__, 2)) . '/cron/centAcl.php',
    ];
    $environment = getenv() + ['ACL_MEASURE_FILE' => $measureFile];

    $start = hrtime(true);
    // The engine output goes to stderr, so that stdout only holds the scenarios table.
    $process = proc_open($command, [0 => ['file', '/dev/null', 'r'], 1 => STDERR, 2 => STDERR], $pipes, null, $environment);
    if (! is_resource($process)) {
        throw new RuntimeException('Cannot start cron/centAcl.php');
    }
    $exitCode = proc_close($process);
    $seconds = (hrtime(true) - $start) / 1e9;

    $measureContent = (string) file_get_contents($measureFile);
    unlink($measureFile);
    if ($exitCode !== 0) {
        throw new RuntimeException("cron/centAcl.php exited with code {$exitCode}");
    }
    $stillFlagged = (int) $configuration->query(
        'SELECT COUNT(*) FROM acl_groups WHERE acl_group_id >= ' . B . " AND acl_group_changed = '1'",
    )->fetchColumn();
    if ($stillFlagged > 0) {
        throw new RuntimeException("cron/centAcl.php did not process {$stillFlagged} dataset groups");
    }
    $measure = $measureContent === '' ? null : json_decode($measureContent, true, flags: JSON_THROW_ON_ERROR);
    if (! is_array($measure)) {
        throw new RuntimeException('cron/centAcl.php ended without writing its measures');
    }

    $stats = null;
    if (is_array($measure['stats'] ?? null)) {
        $stats = [
            'groups' => (int) ($measure['stats']['groups'] ?? 0),
            'skipped' => (int) ($measure['stats']['skipped'] ?? 0),
            'inserted' => (int) ($measure['stats']['inserted'] ?? 0),
            'deleted' => (int) ($measure['stats']['deleted'] ?? 0),
        ];
    }

    return [
        'seconds' => $seconds,
        'peak_bytes' => (int) $measure['peak_bytes'],
        'max_rss_bytes' => (int) $measure['max_rss_kb'] * 1024,
        'stats' => $stats,
    ];
}

/**
 * Checks what a run did to centreon_acl, as the engine reports it.
 *
 * @param array{groups: int, skipped: int, inserted: int, deleted: int}|null $stats null when the engine reported
 *     nothing: its writes cannot be checked, which is a problem
 * @param array{
 *     inserted: int,
 *     deleted: int,
 *     skippedAll?: bool,
 *     skippedSome?: bool,
 *     skippedNone?: bool,
 *     writtenGroups?: int
 * } $expected writtenGroups: the number of groups that must not be skipped
 *
 * @return list<string> the problems found
 */
function checkStats(?array $stats, array $expected): array
{
    if ($stats === null) {
        return ['the run reported no writes ($aclRunStats): they cannot be checked'];
    }
    $problems = [];
    if ($stats['inserted'] !== $expected['inserted'] || $stats['deleted'] !== $expected['deleted']) {
        $problems[] = sprintf(
            'wrote +%d −%d rows instead of +%d −%d',
            $stats['inserted'],
            $stats['deleted'],
            $expected['inserted'],
            $expected['deleted'],
        );
    }
    if (($expected['skippedAll'] ?? false) && $stats['skipped'] !== $stats['groups']) {
        $problems[] = sprintf('skipped %d groups out of %d instead of all', $stats['skipped'], $stats['groups']);
    }
    if (($expected['skippedSome'] ?? false) && $stats['skipped'] === 0) {
        $problems[] = 'skipped no unchanged group';
    }
    if (($expected['skippedNone'] ?? false) && $stats['skipped'] !== 0) {
        $problems[] = sprintf('skipped %d groups instead of none', $stats['skipped']);
    }
    $writtenGroups = $stats['groups'] - $stats['skipped'];
    if (isset($expected['writtenGroups']) && $writtenGroups !== $expected['writtenGroups']) {
        $problems[] = sprintf('wrote %d groups instead of %d', $writtenGroups, $expected['writtenGroups']);
    }

    return $problems;
}

/**
 * @param array{groups: int, skipped: int, inserted: int, deleted: int}|null $stats
 */
function describeStats(?array $stats): string
{
    if ($stats === null) {
        return 'n/a';
    }

    return sprintf(
        '+%s −%s rows, %d/%d groups skipped',
        number_format($stats['inserted']),
        number_format($stats['deleted']),
        $stats['skipped'],
        $stats['groups'],
    );
}

function duration(float $seconds): string
{
    return $seconds < 1 ? sprintf('%d ms', round($seconds * 1000)) : sprintf('%.1f s', $seconds);
}

function megabytes(int $bytes): string
{
    return sprintf('%.1f MB', $bytes / 1048576);
}

/**
 * Builds a Centreon root that runs the cron scripts of $cronDir. centAcl.php loads ../config/centreon.config.php, which
 * sets _CENTREON_PATH_ to the parent of its own directory, then its helpers from _CENTREON_PATH_/cron: the root gets a
 * copy of the configuration and of $cronDir, and links to everything else of this repository.
 *
 * Both compared engines run from such a root: the paths of the files PHP loads take memory, which must not differ
 * between them.
 *
 * @return string the root, to remove with removeTree()
 */
function prepareEngineRoot(string $cronDir): string
{
    if (! is_file($cronDir . '/centAcl.php')) {
        throw new RuntimeException("No centAcl.php in {$cronDir}");
    }
    $projectRoot = dirname(__DIR__, 2);
    $root = sys_get_temp_dir() . '/acl-engine-' . bin2hex(random_bytes(4));
    if (! mkdir($root)) {
        throw new RuntimeException("Cannot create {$root}");
    }
    foreach (scandir($projectRoot) ?: [] as $entry) {
        if (! in_array($entry, ['.', '..', 'cron', 'config'], true)) {
            symlink($projectRoot . '/' . $entry, $root . '/' . $entry);
        }
    }
    copyTree($projectRoot . '/config', $root . '/config');
    copyTree($cronDir, $root . '/cron');

    return $root;
}

function copyTree(string $source, string $target): void
{
    if (! is_dir($target) && ! mkdir($target)) {
        throw new RuntimeException("Cannot create {$target}");
    }
    foreach (scandir($source) ?: [] as $entry) {
        if ($entry === '.' || $entry === '..') {
            continue;
        }
        $from = $source . '/' . $entry;
        if (is_dir($from) && ! is_link($from)) {
            copyTree($from, $target . '/' . $entry);
        } else {
            copy($from, $target . '/' . $entry);
        }
    }
}

/**
 * Removes a baseline root: its links are removed, never followed.
 */
function removeTree(string $path): void
{
    if (is_link($path) || ! is_dir($path)) {
        unlink($path);

        return;
    }
    foreach (scandir($path) ?: [] as $entry) {
        if ($entry !== '.' && $entry !== '..') {
            removeTree($path . '/' . $entry);
        }
    }
    rmdir($path);
}

/**
 * @param list<array{seconds: float, peak_bytes: int}> $runs
 *
 * @return array{seconds: float, peak_bytes: int} the median time and the median PHP peak of the runs
 */
function median(array $runs): array
{
    $seconds = array_column($runs, 'seconds');
    $peaks = array_column($runs, 'peak_bytes');
    sort($seconds);
    sort($peaks);
    $middle = intdiv(count($runs), 2);

    return ['seconds' => $seconds[$middle], 'peak_bytes' => $peaks[$middle]];
}

/**
 * Measures the baseline engine and this engine on scenarios B and C, COMPARISON_RUNS times each, from a freshly loaded
 * dataset. Their runs alternate, in an order that changes at every round, so that both engines meet the same database
 * and machine conditions (background work after a load, other jobs on the machine).
 *
 * Both engines compute the same rows: the fingerprints written by this engine stay valid after a baseline run.
 *
 * @param string $baselineRoot root of the baseline engine, built by prepareEngineRoot()
 * @param string $currentRoot root of this engine, built the same way
 *
 * @return array{
 *     baseline: array{B: array{seconds: float, peak_bytes: int}, C: array{seconds: float, peak_bytes: int}},
 *     current: array{B: array{seconds: float, peak_bytes: int}, C: array{seconds: float, peak_bytes: int}}
 * }
 */
function measureEngines(
    PDO $configuration,
    PDO $storage,
    string $datasetPath,
    string $baselineRoot,
    string $currentRoot,
    string $baselineName,
): array {
    $engines = ['baseline' => $baselineRoot, 'current' => $currentRoot];
    removeDataset($configuration, $storage);
    load($configuration, $datasetPath);
    // First runs, not measured: they fill the table and the fingerprints.
    foreach ($engines as $engineRoot) {
        flagDataset($configuration);
        runEngine($configuration, $engineRoot);
    }

    $runs = ['baseline' => ['B' => [], 'C' => []], 'current' => ['B' => [], 'C' => []]];
    for ($round = 0; $round < COMPARISON_RUNS; $round++) {
        $order = $round % 2 === 0 ? ['baseline', 'current'] : ['current', 'baseline'];
        foreach ($order as $engine) {
            flagDataset($configuration);
            $runs[$engine]['B'][] = runEngine($configuration, $engines[$engine]);
        }
        logRound('B', $round, $baselineName, $runs);
    }
    for ($round = 0; $round < COMPARISON_RUNS; $round++) {
        $order = $round % 2 === 0 ? ['baseline', 'current'] : ['current', 'baseline'];
        foreach ($order as $engine) {
            $change = applySmallChange($configuration);
            flagDataset($configuration);
            $runs[$engine]['C'][] = runEngine($configuration, $engines[$engine]);
            // Back to the original configuration, so that every measured run applies the same change.
            revertSmallChange($configuration, $change);
            flagDataset($configuration);
            runEngine($configuration, $engines[$engine]);
        }
        logRound('C', $round, $baselineName, $runs);
    }

    return [
        'baseline' => ['B' => median($runs['baseline']['B']), 'C' => median($runs['baseline']['C'])],
        'current' => ['B' => median($runs['current']['B']), 'C' => median($runs['current']['C'])],
    ];
}

/**
 * Prints the times of one comparison round on stderr, to see the dispersion behind a median.
 *
 * @param 'B'|'C' $scenario
 * @param array<'baseline'|'current', array<'B'|'C', list<array{seconds: float}>>> $runs
 */
function logRound(string $scenario, int $round, string $baselineName, array $runs): void
{
    fwrite(STDERR, sprintf(
        "Scenario %s, run %d/%d: %s %s, this branch %s\n",
        $scenario,
        $round + 1,
        COMPARISON_RUNS,
        $baselineName,
        duration($runs['baseline'][$scenario][$round]['seconds']),
        duration($runs['current'][$scenario][$round]['seconds']),
    ));
}

/**
 * @return string the change from $before to $after in percent, in bold when it is a gain: "**−85 %**", "+3 %"
 */
function change(float $before, float $after): string
{
    $percent = (int) round(($after / max($before, 0.001) - 1) * 100);
    if ($percent < 0) {
        return '**−' . -$percent . ' %**';
    }

    return ($percent > 0 ? '+' : '') . "{$percent} %";
}

/**
 * @param array{dir: string, ref: string|null, commit: string|null} $baseline
 *
 * @return string where the baseline cron scripts come from, in Markdown
 */
function describeBaseline(array $baseline): string
{
    if ($baseline['ref'] === null) {
        return "the cron scripts of `{$baseline['dir']}`";
    }
    $source = "`centreon/cron` of `{$baseline['ref']}`";
    if ($baseline['commit'] === null) {
        return $source;
    }
    $commit = '`' . substr($baseline['commit'], 0, 10) . '`';
    $server = getenv('GITHUB_SERVER_URL');
    $repository = getenv('GITHUB_REPOSITORY');
    if (is_string($server) && $server !== '' && is_string($repository) && $repository !== '') {
        $commit = "[{$commit}]({$server}/{$repository}/commit/{$baseline['commit']})";
    }

    return "{$source} at commit {$commit}";
}

/**
 * Compares the current engine with the baseline, both measured on the same machine: only their ratio matters.
 *
 * @param array{B: array{seconds: float, peak_bytes: int}, C: array{seconds: float, peak_bytes: int}} $baseline
 * @param array{B: array{seconds: float, peak_bytes: int}, C: array{seconds: float, peak_bytes: int}} $current
 * @param array{dir: string, ref: string|null, commit: string|null} $baselineSource
 *
 * @return array{
 *     section: array{title: string, header: list<string>, rows: list<list<string>>, notes: list<string>},
 *     failed: bool
 * } the report section, and whether a rule is broken
 */
function compareWithBaseline(array $baseline, array $current, array $baselineSource): array
{
    $name = $baselineSource['ref'] === null ? 'Baseline' : "`{$baselineSource['ref']}`";
    $allowedSlowdown = (int) round((ALLOWED_SLOWDOWN - 1) * 100);
    $allowedMemoryGrowth = (int) round((ALLOWED_MEMORY_GROWTH - 1) * 100);
    $rows = [];
    $failed = false;
    foreach (['B' => 'B. Nothing changed', 'C' => 'C. Small change'] as $key => $scenario) {
        $before = $baseline[$key];
        $after = $current[$key];
        $ratio = $after['seconds'] / max($before['seconds'], 0.001);

        $timeChange = change($before['seconds'], $after['seconds']);
        if ($ratio < 1) {
            $timeChange .= sprintf(' (%.1f× faster)', 1 / max($ratio, 0.001));
        }
        $timeResult = $ratio > ALLOWED_SLOWDOWN ? "❌ more than {$allowedSlowdown} % slower" : '✅';
        // The memory used by PHP does not depend on the machine: the margin only absorbs the code a pull request adds
        // to the files the cron loads.
        $memoryResult = $after['peak_bytes'] > $before['peak_bytes'] * ALLOWED_MEMORY_GROWTH
            ? "❌ more than {$allowedMemoryGrowth} % more PHP memory"
            : '✅';
        $failed = $failed || $timeResult !== '✅' || $memoryResult !== '✅';

        $rows[] = [
            $scenario,
            'Time',
            duration($before['seconds']),
            duration($after['seconds']),
            $timeChange,
            $timeResult,
        ];
        $rows[] = [
            $scenario,
            'PHP peak memory',
            megabytes($before['peak_bytes']),
            megabytes($after['peak_bytes']),
            change($before['peak_bytes'], $after['peak_bytes']),
            $memoryResult,
        ];
    }

    return [
        'section' => [
            'title' => "Performance: this branch compared with {$name}",
            'header' => ['Scenario', 'Measure', $name, 'This branch', 'Change', 'Result'],
            'rows' => $rows,
            'notes' => [
                "**{$name}**, the baseline: " . describeBaseline($baselineSource)
                    . '. In CI, the workflow takes it from the branch the pull request targets.',
                '**This branch**: `centreon/cron` of the code under test.',
                'Both run on this machine, on the same dataset: B runs centAcl.php again with nothing changed, C after '
                    . ADDED_HOSTS . ' hosts added to a host group and ' . REMOVED_HOSTS . ' removed. Each scenario runs '
                    . COMPARISON_RUNS . ' times per engine, in alternating order, and the table keeps the median. The '
                    . 'time of a run depends on the machine, the change does not.',
            ],
        ],
        'failed' => $failed,
    ];
}

/**
 * @param array{dir: string, ref: string|null, commit: string|null}|null $baseline the baseline this branch is compared
 *     with, if any
 *
 * @return list<string> every reason for the step to fail, in Markdown
 */
function failureRules(?array $baseline): array
{
    $rules = [
        'the rows computed by this branch differ from the expected ones, in any scenario: a row too many is a '
            . 'visibility leak, a missing row a lost visibility;',
        'a run writes other rows than needed: every row in A and D, none in B, F and G, only the changed ones in C '
            . 'and E;',
        'a run skips other groups than expected: all of them in B and F, none in G, all but the changed one in E '
            . 'and H;',
        'a group whose write fails loses rows, or its flags, or centAcl.php keeps its lock: the next run must write '
            . 'the group again;',
        'a disabled group keeps rows or its fingerprint, or listing the groups of `centreon_acl` reads every row;',
    ];
    if ($baseline !== null) {
        $rules[] = sprintf(
            'this branch is more than %d %% slower than %s, or uses more than %d %% more PHP memory, in B or C;',
            round((ALLOWED_SLOWDOWN - 1) * 100),
            $baseline['ref'] === null ? 'the baseline' : "`{$baseline['ref']}`",
            round((ALLOWED_MEMORY_GROWTH - 1) * 100),
        );
    }
    $rules[] = 'centAcl.php stops on an error, or leaves an access group of the dataset unprocessed.';

    return $rules;
}

/**
 * @param list<array{title: string, header: list<string>, rows: list<list<string>>, notes: list<string>}> $sections
 * @param list<string> $failureRules
 *
 * @return string the report for the GitHub job summary, which renders Markdown
 */
function renderMarkdown(string $title, array $sections, array $failureRules): string
{
    $lines = ["### {$title}"];
    foreach ($sections as $section) {
        array_push(
            $lines,
            '',
            "#### {$section['title']}",
            '',
            '| ' . implode(' | ', $section['header']) . ' |',
            '|' . str_repeat(' --- |', count($section['header'])),
        );
        foreach ($section['rows'] as $row) {
            $lines[] = '| ' . implode(' | ', $row) . ' |';
        }
        if ($section['notes'] !== []) {
            array_push($lines, '', 'How to read it:', '');
            foreach ($section['notes'] as $note) {
                $lines[] = "- {$note}";
            }
        }
    }
    array_push($lines, '', '#### When the step fails', '');
    foreach ($failureRules as $rule) {
        $lines[] = "- {$rule}";
    }

    return implode("\n", $lines) . "\n\n";
}

/**
 * @param list<array{title: string, header: list<string>, rows: list<list<string>>, notes: list<string>}> $sections
 * @param list<string> $failureRules
 *
 * @return string the report for the job log, which shows plain text: bordered tables with aligned columns
 */
function renderText(string $title, array $sections, array $failureRules): string
{
    // Widths in terminal columns: an emoji such as ✅ takes two.
    $lines = [$title, str_repeat('=', mb_strwidth($title))];
    foreach ($sections as $section) {
        $sectionTitle = plainText($section['title']);
        $table = array_map(
            static fn (array $row): array => array_map(plainText(...), $row),
            [$section['header'], ...$section['rows']],
        );
        $widths = [];
        foreach ($table as $row) {
            foreach ($row as $column => $cell) {
                $widths[$column] = max($widths[$column] ?? 0, mb_strwidth($cell));
            }
        }
        $border = '+-' . implode('-+-', array_map(static fn (int $width): string => str_repeat('-', $width), $widths)) . '-+';

        array_push($lines, '', $sectionTitle, str_repeat('-', mb_strwidth($sectionTitle)), '', $border);
        foreach ($table as $index => $row) {
            $cells = [];
            foreach ($row as $column => $cell) {
                $cells[] = $cell . str_repeat(' ', $widths[$column] - mb_strwidth($cell));
            }
            $lines[] = '| ' . implode(' | ', $cells) . ' |';
            // A border under the header, and one under the last row.
            if ($index === 0 || $index === count($table) - 1) {
                $lines[] = $border;
            }
        }
        if ($section['notes'] !== []) {
            array_push($lines, '', 'How to read it:');
            foreach ($section['notes'] as $note) {
                $lines[] = '- ' . plainText($note);
            }
        }
    }
    array_push($lines, '', 'When the step fails', '-------------------', '');
    foreach ($failureRules as $rule) {
        $lines[] = '- ' . plainText($rule);
    }

    return implode("\n", $lines) . "\n\n";
}

/**
 * @return string $markdown without emphasis nor code marks, and its links spelled out
 */
function plainText(string $markdown): string
{
    $text = preg_replace('/\[([^\]]*)\]\(([^)]*)\)/', '$1 ($2)', $markdown) ?? $markdown;

    return strtr($text, ['**' => '', '`' => '']);
}

/**
 * @param list<string> $arguments the command line
 *
 * @return array{dir: string, ref: string|null, commit: string|null}|null the baseline given with --baseline, if any:
 *     its cron directory, and the Git branch and commit it comes from when known
 */
function baselineOptions(array $arguments): ?array
{
    $values = [];
    $options = array_slice($arguments, 3);
    while ($options !== []) {
        $name = array_shift($options);
        if (! in_array($name, ['--baseline', '--baseline-ref', '--baseline-commit'], true)) {
            throw new RuntimeException("Unknown option: {$name}");
        }
        $value = array_shift($options);
        if ($value === null || $value === '') {
            throw new RuntimeException("{$name} needs a value");
        }
        $values[$name] = $value;
    }
    if (isset($values['--baseline-commit']) && preg_match('/^[0-9a-f]{7,64}$/', $values['--baseline-commit']) !== 1) {
        throw new RuntimeException("Invalid commit: {$values['--baseline-commit']}");
    }
    if (! isset($values['--baseline'])) {
        if ($values !== []) {
            throw new RuntimeException('--baseline-ref and --baseline-commit need --baseline');
        }

        return null;
    }

    return [
        'dir' => $values['--baseline'],
        'ref' => $values['--baseline-ref'] ?? null,
        'commit' => $values['--baseline-commit'] ?? null,
    ];
}

/**
 * @param array{dir: string, ref: string|null, commit: string|null}|null $baseline
 */
function scenarios(PDO $configuration, PDO $storage, string $size, ?array $baseline = null): int
{
    if (preg_match('/^[A-Z]{1,3}$/', $size) !== 1) {
        throw new RuntimeException("Invalid dataset size: {$size}");
    }
    $datasetPath = __DIR__ . "/dataset-{$size}.sql";
    $expectedPath = __DIR__ . "/expected-{$size}.sql";
    $expectedFile = basename($expectedPath);
    foreach ([$datasetPath, $expectedPath] as $path) {
        if (! is_file($path)) {
            throw new RuntimeException("Missing file: {$path}");
        }
    }

    removeDataset($configuration, $storage);
    load($configuration, $datasetPath);
    $results = [];

    fwrite(STDERR, "Scenario A: empty table\n");
    flagDataset($configuration);
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $expectedPath);
    // Every row is new.
    $problems = checkStats($metrics['stats'], ['inserted' => $comparison['expected'], 'deleted' => 0]);
    $results[] = ['A. Empty table', $metrics, $comparison, $problems, "same as `{$expectedFile}`"];

    fwrite(STDERR, "Scenario B: nothing changed\n");
    flagDataset($configuration);
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $expectedPath);
    // Every group is skipped thanks to its fingerprint: no row written.
    $problems = checkStats($metrics['stats'], ['inserted' => 0, 'deleted' => 0, 'skippedAll' => true]);
    $results[] = ['B. Nothing changed', $metrics, $comparison, $problems, "same as `{$expectedFile}`"];

    fwrite(STDERR, "Scenario C: small change\n");
    applySmallChange($configuration);
    flagDataset($configuration);
    $metrics = runEngine($configuration);
    // Only the rows that changed are written: the difference with the rows before the change.
    $changes = compare($storage, $expectedPath);
    $problems = checkStats($metrics['stats'], [
        'inserted' => count($changes['unexpected']),
        'deleted' => count($changes['missing']),
        'skippedSome' => true,
    ]);
    $afterChangePath = tempnam(sys_get_temp_dir(), 'acl-after-change-');
    $afterChange = $afterChangePath === false ? false : fopen($afterChangePath, 'w');
    if ($afterChangePath === false || $afterChange === false) {
        throw new RuntimeException('Cannot create a temporary file');
    }
    writeExpected($storage, $afterChange);
    fclose($afterChange);
    // Reference: a full recompute of the changed configuration, on an empty table.
    clearComputedRows($storage);
    flagDataset($configuration);
    runEngine($configuration);
    $comparison = compare($storage, $afterChangePath);
    $results[] = ['C. Small change', $metrics, $comparison, $problems, 'same as a full recompute'];

    fwrite(STDERR, "Scenario D: rows deleted outside the cron\n");
    // A support procedure empties centreon_acl before "Reload ACL": the fingerprints stay, every row must come back.
    $storage->exec('DELETE FROM centreon_acl WHERE group_id >= ' . B);
    flagDataset($configuration);
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $afterChangePath);
    $problems = checkStats($metrics['stats'], ['inserted' => $comparison['expected'], 'deleted' => 0]);
    $results[] = ['D. Rows deleted outside the cron', $metrics, $comparison, $problems, 'same as before the deletion'];

    fwrite(STDERR, "Scenario E: a row inserted outside the cron\n");
    // Its fingerprint removed, the group is compared again: the row it is not granted goes.
    insertRowOutsideCron($storage, FIRST_DATASET_GROUP_ID);
    flagDataset($configuration);
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $afterChangePath);
    $problems = checkStats($metrics['stats'], ['inserted' => 0, 'deleted' => 1, 'writtenGroups' => 1]);
    $results[] = ['E. Row inserted outside the cron', $metrics, $comparison, $problems, 'same as before the insert'];

    fwrite(STDERR, "Scenario F: a disabled access group\n");
    $staleGroupId = FIRST_DATASET_GROUP_ID;
    flagDataset($configuration);
    // Not flagged: centAcl.php only recomputes the active groups.
    $configuration->exec(
        "UPDATE acl_groups SET acl_group_activate = '0', acl_group_changed = '0' WHERE acl_group_id = {$staleGroupId}",
    );
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $afterChangePath);
    $problems = [
        ...checkStats($metrics['stats'], ['inserted' => 0, 'deleted' => 0, 'skippedAll' => true]),
        ...checkStaleGroupRemoved($storage, $staleGroupId),
        ...checkStaleGroupListing($storage),
    ];
    // The rows of the disabled group must be missing (checked above): the comparison covers the other groups.
    $comparison['missing'] = array_values(array_filter(
        $comparison['missing'],
        static fn (array $row): bool => $row['group_id'] !== $staleGroupId,
    ));
    $results[] = ['F. Disabled access group', $metrics, $comparison, $problems, 'its rows removed, the others kept'];
    $configuration->exec("UPDATE acl_groups SET acl_group_activate = '1' WHERE acl_group_id = {$staleGroupId}");
    flagDataset($configuration);
    runEngine($configuration);

    fwrite(STDERR, "Scenario G: no fingerprint table\n");
    // Right after a package upgrade, the cron runs before the database upgrade creates the table.
    $storage->exec('RENAME TABLE centreon_acl_checksum TO centreon_acl_checksum_hidden');
    try {
        flagDataset($configuration);
        $metrics = runEngine($configuration);
    } finally {
        $storage->exec('RENAME TABLE centreon_acl_checksum_hidden TO centreon_acl_checksum');
    }
    $comparison = compare($storage, $afterChangePath);
    $problems = checkStats($metrics['stats'], ['inserted' => 0, 'deleted' => 0, 'skippedNone' => true]);
    $results[] = ['G. No fingerprint table', $metrics, $comparison, $problems, 'same rows, no group skipped'];

    fwrite(STDERR, "Scenario H: a write error, then the next run (the error below is expected)\n");
    $failingGroupId = FIRST_DATASET_GROUP_ID + 1;
    $rowCountBefore = prepareWriteError($storage, $failingGroupId);
    try {
        // Like "Reload ACL": only the resource accesses are flagged, not the groups.
        $configuration->exec("UPDATE acl_resources SET changed = '1' WHERE acl_res_id >= " . B);
        runEngine($configuration);
    } finally {
        $storage->exec('ALTER TABLE centreon_acl DROP CONSTRAINT ' . WRITE_ERROR_CONSTRAINT);
    }
    $failureProblems = checkFailedWrite($configuration, $storage, $failingGroupId, $rowCountBefore);
    $metrics = runEngine($configuration);
    $comparison = compare($storage, $afterChangePath);
    unlink($afterChangePath);
    $problems = [
        ...$failureProblems,
        ...checkStats($metrics['stats'], ['inserted' => 1, 'deleted' => 0, 'writtenGroups' => 1]),
    ];
    $results[] = ['H. Write error, then retried', $metrics, $comparison, $problems, 'rows kept, then written again'];

    $scenarioSection = [
        'title' => 'This branch, scenario by scenario',
        'header' => ['Scenario', 'centAcl.php', 'PHP peak', 'Max RSS', 'Writes', 'Rows checked', 'Result'],
        'rows' => [],
        'notes' => [
            'Rows checked: the `centreon_acl` rows computed for the access groups of the dataset, each compared with '
                . "the expected rows, both ways: `{$expectedFile}` in A and B, a full recompute on an empty table "
                . 'after the change of C from C on (without the disabled group in F).',
            'Writes: the rows the run inserted and deleted, and the access groups it skipped thanks to their '
                . 'fingerprint.',
        ],
    ];
    $failed = false;
    foreach ($results as [$scenario, $metrics, $comparison, $problems, $success]) {
        if (! isIdentical($comparison)) {
            $failed = true;
            fwrite(STDERR, "{$scenario}:\n");
            report('Unexpected rows (visibility leak)', $comparison['unexpected']);
            report('Missing rows (lost visibility)', $comparison['missing']);
        }
        if ($problems !== []) {
            $failed = true;
            fwrite(STDERR, "{$scenario}: " . implode('; ', $problems) . "\n");
        }
        $status = match (true) {
            ! isIdentical($comparison) => sprintf(
                '❌ %d unexpected, %d missing',
                count($comparison['unexpected']),
                count($comparison['missing']),
            ),
            $problems !== [] => '❌ ' . implode('; ', $problems),
            default => "✅ {$success}",
        };
        $scenarioSection['rows'][] = [
            $scenario,
            duration($metrics['seconds']),
            megabytes($metrics['peak_bytes']),
            megabytes($metrics['max_rss_bytes']),
            describeStats($metrics['stats']),
            number_format($comparison['computed']),
            $status,
        ];
    }
    $sections = [$scenarioSection];

    // The comparison with the baseline comes first: it is what a pull request changes.
    if ($baseline !== null) {
        $baselineName = $baseline['ref'] ?? 'baseline';
        fwrite(STDERR, sprintf(
            "Comparison with %s%s, cron scripts in %s\n",
            $baselineName,
            $baseline['commit'] === null ? '' : ' at commit ' . substr($baseline['commit'], 0, 10),
            $baseline['dir'],
        ));
        $roots = [];
        try {
            $roots['baseline'] = prepareEngineRoot($baseline['dir']);
            $roots['current'] = prepareEngineRoot(dirname(__DIR__, 2) . '/cron');
            $measures = measureEngines(
                $configuration,
                $storage,
                $datasetPath,
                $roots['baseline'],
                $roots['current'],
                $baselineName,
            );
        } finally {
            foreach ($roots as $root) {
                removeTree($root);
            }
        }
        $comparison = compareWithBaseline($measures['baseline'], $measures['current'], $baseline);
        $failed = $failed || $comparison['failed'];
        array_unshift($sections, $comparison['section']);
    }

    // The job log shows plain text, the job summary renders Markdown.
    $title = "ACL computation on dataset {$size}";
    $failureRules = failureRules($baseline);
    echo renderText($title, $sections, $failureRules);
    $summaryPath = getenv('GITHUB_STEP_SUMMARY');
    if (is_string($summaryPath) && $summaryPath !== '') {
        file_put_contents($summaryPath, renderMarkdown($title, $sections, $failureRules), FILE_APPEND);
    }
    // In a GitHub workflow only: outside of it, the summary file is a plain Markdown copy of the report.
    $runId = getenv('GITHUB_RUN_ID');
    if (is_string($summaryPath) && $summaryPath !== '' && is_string($runId) && $runId !== '') {
        $runUrl = sprintf('%s/%s/actions/runs/%s', getenv('GITHUB_SERVER_URL'), getenv('GITHUB_REPOSITORY'), $runId);
        echo "The same report, with rendered tables, is in the summary of the workflow run: {$runUrl}\n";
    }

    return $failed ? EXIT_DIFFERENT : EXIT_IDENTICAL;
}

$usage = 'Usage: php qualify.php load <dataset.sql> | export | check <expected.sql> '
    . "| scenarios <size> [--baseline <cron directory> [--baseline-ref <branch>] [--baseline-commit <sha>]]\n";
try {
    // Loaded at the top level: centreon.config.php defines $conf_centreon in the scope that includes it.
    $configFile = dirname(__DIR__, 2) . '/config/centreon.config.php';
    if (! is_file($configFile)) {
        throw new RuntimeException("Missing Centreon configuration: {$configFile}");
    }
    require_once $configFile;
    if (! isset($conf_centreon) || ! is_array($conf_centreon)) {
        throw new RuntimeException('Missing database settings in ' . _CENTREON_ETC_ . '/centreon.conf.php');
    }

    $exitCode = match ($argv[1] ?? '') {
        'load' => isset($argv[2]) ? load(connect($conf_centreon, 'db'), $argv[2]) : null,
        'export' => export(connect($conf_centreon, 'dbcstg')),
        'check' => isset($argv[2]) ? check(connect($conf_centreon, 'dbcstg'), $argv[2]) : null,
        'scenarios' => isset($argv[2])
            ? scenarios(connect($conf_centreon, 'db'), connect($conf_centreon, 'dbcstg'), $argv[2], baselineOptions($argv))
            : null,
        default => null,
    };
} catch (Throwable $exception) {
    fwrite(STDERR, $exception->getMessage() . "\n");

    exit(EXIT_ERROR);
}
if ($exitCode === null) {
    fwrite(STDERR, $usage);

    exit(EXIT_ERROR);
}

exit($exitCode);
