// Generates playwright/stories.d.ts, the typed registry of the story ids accepted by mount().
// Ids follow the gallery resolution rules: full id plus every unambiguous suffix.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const playwrightDir = dirname(fileURLToPath(import.meta.url));
const sourceDir = join(playwrightDir, '../www/front_src/src');
const outputFile = join(playwrightDir, 'stories.d.ts');

const exportPattern = /^export\s+(?:const|function)\s+([A-Za-z_$][\w$]*)/gm;

const findStoryFiles = (directory) =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      return entry.name === 'node_modules' ? [] : findStoryFiles(path);
    }

    return entry.name.endsWith('.story.tsx') ? [path] : [];
  });

const stories = findStoryFiles(sourceDir)
  .sort()
  .flatMap((file, moduleIndex) => {
    const modulePath = relative(sourceDir, file)
      .split(sep)
      .join('/')
      .replace(/\.story\.tsx$/, '');
    const exportNames = [
      ...readFileSync(file, 'utf8').matchAll(exportPattern)
    ].map(([, name]) => name);

    return exportNames.map((exportName) => ({
      exportName,
      id: `${modulePath}/${exportName}`,
      importPath: `../www/front_src/src/${modulePath}.story`,
      moduleAlias: `Story${moduleIndex}`
    }));
  });

const suffixesOf = (id) =>
  id.split('/').map((_, index, parts) => parts.slice(index).join('/'));

const suffixCount = new Map();
for (const { id } of stories) {
  for (const suffix of suffixesOf(id)) {
    suffixCount.set(suffix, (suffixCount.get(suffix) ?? 0) + 1);
  }
}

const imports = [
  ...new Map(stories.map((story) => [story.moduleAlias, story.importPath]))
].map(([alias, path]) => `import type * as ${alias} from '${path}';`);

const entries = stories.flatMap(({ id, moduleAlias, exportName }) =>
  suffixesOf(id)
    .filter((suffix) => suffixCount.get(suffix) === 1)
    .map((suffix) => `    '${suffix}': typeof ${moduleAlias}.${exportName};`)
);

writeFileSync(
  outputFile,
  [
    '// Generated by playwright/generate-stories.mjs, do not edit.',
    ...imports,
    '',
    "declare module '@playwright/test' {",
    '  interface Stories {',
    ...entries,
    '  }',
    '}',
    ''
  ].join('\n')
);

// Keeps the generated file lint-clean (import order, line width).
execFileSync(join(playwrightDir, '../node_modules/.bin/biome'), [
  'check',
  '--write',
  outputFile
]);

process.stdout.write(
  `${stories.length} stories, ${entries.length} story ids -> ${relative(process.cwd(), outputFile)}\n`
);
