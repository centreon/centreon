declare(strict_types=1);

namespace Core\Gorgone\Infrastructure\Repository;

use Core\Gorgone\Application\Repository\ReadGorgoneConfigurationRepositoryInterface;
use Core\Gorgone\Application\Repository\ReadGorgoneNodeRepositoryInterface;
use Core\Gorgone\Application\Service\GorgoneCommandService;

/**
 * Reads the configuration files generated by Centreon for a poller.
 */
final class FsReadGorgoneConfigurationRepository implements ReadGorgoneConfigurationRepositoryInterface
{
    private const VMWARE_FILE = 'centreon_vmware.json';
    private const TRAPS_FILE = 'centreontrapd.sdb';

    /**
     * @param string $cacheDirectory Centreon cache directory (holds "config/{engine,broker,vmware}/<node id>")
     * @param ReadGorgoneNodeRepositoryInterface $readNodeRepository
     */
    public function __construct(
        private readonly string $cacheDirectory,
        private readonly ReadGorgoneNodeRepositoryInterface $readNodeRepository,
    ) {
    }

    /**
     * @inheritDoc
     */
    public function findFiles(int $nodeId, string $target): array
    {
        $configDirectory = rtrim($this->cacheDirectory, '/') . '/config';

        return match ($target) {
            GorgoneCommandService::TARGET_ENGINE => $this->readDirectory("{$configDirectory}/engine/{$nodeId}"),
            GorgoneCommandService::TARGET_BROKER => $this->readDirectory("{$configDirectory}/broker/{$nodeId}"),
            GorgoneCommandService::TARGET_VMWARE => $this->readFile(
                "{$configDirectory}/vmware/{$nodeId}/" . self::VMWARE_FILE
            ),
            GorgoneCommandService::TARGET_CENTREONTRAPD => $this->readTrapsDatabase($nodeId),
            default => throw new \InvalidArgumentException(
                sprintf('Unknown configuration target "%s"', $target)
            ),
        };
    }

    /**
     * @param int $nodeId
     *
     * @throws \Throwable
     *
     * @return array<string, string>
     */
    private function readTrapsDatabase(int $nodeId): array
    {
        foreach ($this->readNodeRepository->findTrapsDirectories($nodeId) as $directory) {
            $files = $this->readFile("{$directory}/{$nodeId}/" . self::TRAPS_FILE);
            if ($files !== []) {
                return $files;
            }
        }

        return [];
    }

    /**
     * @param string $path
     *
     * @throws \RuntimeException
     *
     * @return array<string, string> empty when the file does not exist
     */
    private function readFile(string $path): array
    {
        if (is_link($path) || ! is_file($path)) {
            return [];
        }

        return [basename($path) => $this->getContent($path)];
    }

    /**
     * @param string $directory
     *
     * @throws \RuntimeException
     *
     * @return array<string, string> regular files of the directory, sub-directories included
     */
    private function readDirectory(string $directory): array
    {
        if (! is_dir($directory)) {
            return [];
        }

        $files = [];
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS)
        );
        /** @var \SplFileInfo $file */
        foreach ($iterator as $file) {
            if ($file->isLink() || ! $file->isFile()) {
                continue;
            }
            $name = mb_substr($file->getPathname(), mb_strlen($directory, '8bit') + 1, null, '8bit');
            $files[str_replace(DIRECTORY_SEPARATOR, '/', $name)] = $this->getContent($file->getPathname());
        }
        ksort($files);

        return $files;
    }

    /**
     * @param string $path
     *
     * @throws \RuntimeException
     *
     * @return string
     */
    private function getContent(string $path): string
    {
        $content = @file_get_contents($path);
        if ($content === false) {
            throw new \RuntimeException(sprintf('Cannot read the configuration file "%s"', $path));
        }

        return $content;
    }
}
